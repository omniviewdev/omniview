import React from 'react';
import { act, cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react';
import { afterEach, describe, expect, it, vi } from 'vitest';
const api = vi.hoisted(() => ({ connections: vi.fn(), definitions: vi.fn(), sources: vi.fn(), save: vi.fn(), test: vi.fn() }));
vi.mock('@omniviewdev/runtime/api', () => ({ MetricClient: { GetProviderConnections: api.connections, GetMetricDefinitions: api.definitions, GetDataSources: api.sources, SaveProviderConnection: api.save, TestProviderConnection: api.test } }));
vi.mock('./ValidationContext', () => ({ default: () => null }));
vi.mock('./Mappings', () => ({ Mappings: () => null }));
import Settings from './Settings';
afterEach(() => { cleanup(); vi.resetAllMocks(); });
describe('global mapping datasource context', () => {
  it('allows manual UID after denied discovery and clears UID across provider instances', async () => {
    api.connections.mockResolvedValue([{ id: 'one', name: 'One', url: 'https://one.test' }, { id: 'two', name: 'Two', url: 'https://two.test' }]);
    api.definitions.mockResolvedValue([]);
    api.sources.mockRejectedValue(new Error('403 list denied'));
    render(<Settings />);
    fireEvent.click(screen.getByRole('tab', { name: 'Global mappings' }));
    await waitFor(() => expect(screen.getByRole('option', { name: 'One' })).toBeInTheDocument());
    fireEvent.change(screen.getByRole('combobox', { name: 'Provider connection' }), { target: { value: 'one' } });
    await waitFor(() => expect(screen.getByRole('alert')).toHaveTextContent('403 list denied'));
    const manual = screen.getByRole('textbox', { name: 'Prometheus datasource UID' });
    fireEvent.change(manual, { target: { value: 'manual-prom' } });
    expect(manual).toHaveValue('manual-prom');
    expect(screen.getByRole('alert')).toHaveTextContent('403 list denied');
    fireEvent.change(screen.getByRole('combobox', { name: 'Provider connection' }), { target: { value: 'two' } });
    expect(manual).toHaveValue('');
    await waitFor(() => expect(api.sources).toHaveBeenCalledWith('grafana', 'two'));
  });
  it('never carries an entered credential across editor identities and locks controls during save', async () => {
    const one = { id: 'one', name: 'One', url: 'https://one.test', kind: 'grafana', has_credentials: true, public_config: { credentialKind: 'grafana-service-account' } };
    const two = { ...one, id: 'two', name: 'Two', url: 'https://two.test' };
    api.connections.mockResolvedValue([one, two]);
    api.definitions.mockResolvedValue([]); api.sources.mockResolvedValue([]);
    api.test.mockResolvedValue({ valid: true, issues: [] });
    const pendingSave = Promise.withResolvers<typeof two>();
    api.save.mockReturnValue(pendingSave.promise);
    render(<Settings />);
    await waitFor(() => expect(screen.getAllByRole('button', { name: 'Manage' })).toHaveLength(2));
    fireEvent.click(screen.getAllByRole('button', { name: 'Manage' })[0]);
    fireEvent.click(screen.getByRole('button', { name: 'Continue' }));
    fireEvent.change(screen.getByLabelText('Read token'), { target: { value: 'one-private-token' } });
    fireEvent.click(screen.getAllByRole('button', { name: 'Manage' })[1]);
    fireEvent.click(screen.getByRole('button', { name: 'Continue' }));
    expect(screen.getByLabelText('Read token')).toHaveValue('');
    fireEvent.click(screen.getByRole('button', { name: 'Continue' }));
    fireEvent.click(screen.getByRole('button', { name: 'Save and test' }));
    await waitFor(() => expect(api.save).toHaveBeenCalledTimes(1));
    expect(api.save.mock.calls[0][1].connection.id).toBe('two');
    expect(api.save.mock.calls[0][1]).not.toHaveProperty('credential');
    expect(screen.getByRole('button', { name: 'Connect Grafana' })).toBeDisabled();
    expect(screen.getAllByRole('button', { name: 'Manage' })[0]).toBeDisabled();
    expect(screen.getByRole('button', { name: 'Cancel' })).toBeDisabled();
    await act(async () => { pendingSave.resolve(two); });
    await waitFor(() => expect(screen.getByRole('status')).toHaveTextContent('Connection saved and reachable'));
  });
});
