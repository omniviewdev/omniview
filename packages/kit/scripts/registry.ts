/**
 * The two registries of the kit, generated from the part directories so that adding a part never edits a shared file.
 *
 *   - the public entry `src/index.ts`: one `export *` per part directory (`src/components/<Part>/index.ts`, the part's own public
 *     exports) and per foundation directory (`src/theme`, `src/shared`), in a stable sorted order;
 *   - the examples registry `src/generated/examples.ts`: one import per `<Part>.examples.tsx` found in a part directory, in a stable
 *     sorted order, keyed by the file's name (`DataTable.parity.examples.tsx` is `DataTableParity`).
 *
 * `generate.ts` writes both, and fails `--check` when a committed file differs from what the directories produce.
 */
import { readdir } from 'node:fs/promises';
import path from 'node:path';

/**
 * Directories outside `src/components` that hold public exports of their own, each with an `index.ts`; the value says whether the
 * directory exports types only (`export type *`, which the lint rule on type-only exports asks for). A new part never goes here.
 */
export const FOUNDATION_DIRECTORIES: Readonly<Record<string, 'types' | 'values'>> = { shared: 'types', theme: 'values' };

const EXAMPLES_SUFFIX = '.examples.tsx';

export type ExampleFile = {
  /** The key in the registry: the public name of the part (or of the group of examples). */
  readonly key: string;
  /** The module specifier of the file, relative to `src/generated`, without an extension. */
  readonly module: string;
};

export type PublicDirectory = { readonly directory: string; readonly typesOnly: boolean };

export type Layout = {
  /** Directories, relative to `src` and in POSIX form, whose `index.ts` is part of the public entry. */
  readonly publicDirectories: readonly PublicDirectory[];
  readonly examples: readonly ExampleFile[];
};

const byCodePoint = (a: string, b: string) => (a < b ? -1 : a > b ? 1 : 0);

/** `DataTable.parity.examples.tsx` -> `DataTableParity`; `Button.examples.tsx` -> `Button`. */
export function exampleKey(file: string): string {
  const stem = file.slice(0, -EXAMPLES_SUFFIX.length);
  return stem
    .split('.')
    .map((segment) => segment.charAt(0).toUpperCase() + segment.slice(1))
    .join('');
}

/** What the part directories hold: `index.ts` and examples files, read from `src`. */
export async function scanLayout(srcRoot: string): Promise<Layout> {
  const publicDirectories: PublicDirectory[] = [];
  const examples: ExampleFile[] = [];

  for (const [directory, kind] of Object.entries(FOUNDATION_DIRECTORIES)) {
    const entries = await readdir(path.join(srcRoot, directory));
    if (!entries.includes('index.ts')) {
      throw new Error(`The foundation directory src/${directory} has no index.ts`);
    }

    publicDirectories.push({ directory, typesOnly: kind === 'types' });
  }

  const parts = await readdir(path.join(srcRoot, 'components'), { withFileTypes: true });
  for (const part of parts) {
    if (!part.isDirectory()) {
      continue;
    }

    const entries = await readdir(path.join(srcRoot, 'components', part.name));
    // A directory without an index.ts is internal to its neighbours (TableFit): nothing of it is public.
    if (entries.includes('index.ts')) {
      publicDirectories.push({ directory: `components/${part.name}`, typesOnly: false });
    }

    for (const entry of entries) {
      if (entry.endsWith(EXAMPLES_SUFFIX)) {
        examples.push({ key: exampleKey(entry), module: `../components/${part.name}/${entry.slice(0, -'.tsx'.length)}` });
      }
    }
  }

  return { publicDirectories, examples };
}

/** Throws when two examples files claim one key: the registry would silently keep one of them. */
function sortedExamples(layout: Layout): readonly ExampleFile[] {
  const seen = new Map<string, string>();
  for (const example of layout.examples) {
    const other = seen.get(example.key);
    if (other !== undefined) {
      throw new Error(`Two examples files are both called ${example.key}: ${other} and ${example.module}`);
    }

    seen.set(example.key, example.module);
  }

  return [...layout.examples].sort((a, b) => byCodePoint(a.key, b.key));
}

export function renderBarrel(layout: Layout): string {
  const lines = [...layout.publicDirectories]
    .sort((a, b) => byCodePoint(a.directory, b.directory))
    .map(({ directory, typesOnly }) => `export ${typesOnly ? 'type ' : ''}* from './${directory}';`);
  return [
    '// GENERATED by scripts/generate.ts from the part directories. Do not edit: CI fails when this file is stale.',
    '//',
    '// The public surface. Everything a plugin or the host may import from "@omniviewdev/kit" is exported here and nowhere else;',
    '// `api/kit.api.md` is the report of exactly this file, and CI fails when the two differ.',
    '//',
    '// To add a part, add a directory `src/components/<Part>/` with an `index.ts` (its public exports); never edit this file.',
    ...lines,
    '',
  ].join('\n');
}

/** The import binding of an examples file: a valid identifier that can never be `partExamples`, the registry's own export. */
export const bindingOf = (key: string) => `${key.replace(/[^A-Za-z0-9_$]/g, '_').replace(/^[0-9]/, '_$&').replace(/^./, (first) => first.toLowerCase())}Module`;

const PLAIN_KEY = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

/** An object key as source: bare when it is a plain identifier, a string literal otherwise (`DataTableHigh-contrast`). */
export const keyLiteral = (key: string) => (PLAIN_KEY.test(key) ? key : `'${key.replaceAll('\\', '\\\\').replaceAll('\'', '\\\'')}'`);

export function renderExamplesRegistry(layout: Layout): string {
  const examples = sortedExamples(layout);
  const bindings = new Map<string, string>();
  for (const example of examples) {
    const binding = bindingOf(example.key);
    const other = bindings.get(binding);
    if (other !== undefined) {
      throw new Error(`Two examples files give the same import name ${binding}: ${other} and ${example.key}`);
    }

    bindings.set(binding, example.key);
  }

  return [
    '// GENERATED by scripts/generate.ts from the `<Part>.examples.tsx` files. Do not edit: CI fails when this file is stale.',
    '//',
    '// To add examples, add `<Part>.examples.tsx` to the part directory; never edit this file or src/examples.ts.',
    ...examples.map((example) => `import * as ${bindingOf(example.key)} from '${example.module}';`),
    '',
    '/** The examples of every part, keyed by the part\'s public name and sorted by it. */',
    'export const partExamples = {',
    ...examples.map((example) => `  ${keyLiteral(example.key)}: ${bindingOf(example.key)},`),
    '};',
    '',
  ].join('\n');
}
