import {
  COLOR_ROLE_GROUPS,
  CONTROL_HEIGHT,
  DEFAULT_DENSITY,
  DEFAULT_TEXT_SIZE,
  DENSITIES,
  DENSITY_TOKENS,
  FONT_SIZES,
  FONTS,
  LINE_HEIGHTS,
  RADII,
  SHADOWS,
  SPACING,
  TEXT_SIZES,
  TOKEN_PREFIX,
} from './manifest.ts';
import type { ColorRoleGroup, Density } from './manifest.ts';
import type { ThemeDefinition } from './schema.ts';

const BANNER = 'Generated by scripts/generate.ts from tokens/manifest.ts and tokens/themes.ts. Do not edit.';

const name = (suffix: string): string => `${TOKEN_PREFIX}${suffix}`;
const px = (value: number): string => `${value}px`;

const densityTokenNames = Object.keys(DENSITY_TOKENS) as Array<keyof typeof DENSITY_TOKENS>;
const groups = Object.entries(COLOR_ROLE_GROUPS) as Array<[ColorRoleGroup, readonly string[]]>;

/** Every token name the CSS defines, in the order it declares them. The typed `TokenName` is exactly this list. */
export function tokenNames(): readonly string[] {
  return [
    name('font-ui'),
    name('font-code'),
    name('font-features'),
    name('text-scale'),
    ...FONT_SIZES.map((size) => name(`fs-${size}`)),
    ...LINE_HEIGHTS.map((size) => name(`lh-${size}`)),
    ...SPACING.map((step) => name(`spacing-${step}`)),
    ...Object.keys(RADII).map((role) => name(`radius-${role}`)),
    name('control-height'),
    ...Object.keys(SHADOWS).map((role) => name(`shadow-${role}`)),
    ...densityTokenNames.map((token) => name(token)),
    ...groups.flatMap(([, roles]) => roles.map((role) => name(role))),
  ];
}

function declarations(entries: ReadonlyArray<readonly [string, string]>, indent: string): string {
  return entries.map(([property, value]) => `${indent}${property}: ${value};`).join('\n');
}

function densityEntries(density: Density): Array<[string, string]> {
  return densityTokenNames.map((token) => [name(token), px(DENSITY_TOKENS[token][density])]);
}

/** The token stylesheet: every custom property the kit defines, inside the `ov.tokens` layer. */
export function renderTokensCss(themes: readonly ThemeDefinition[], defaultThemeId: string): string {
  const blocks: string[] = [];

  blocks.push(
    [
      '  /* Type, geometry, elevation and spacing. A theme sets colour only; type, density and text size are the other axes. */',
      '  :root {',
      declarations(
        [
          [name('font-ui'), FONTS.ui],
          [name('font-code'), FONTS.code],
          [name('font-features'), FONTS.features],
          [name('text-scale'), '1'],
          ...FONT_SIZES.map((size): [string, string] => [name(`fs-${size}`), `calc(${px(size)} * var(${name('text-scale')}))`]),
          ...LINE_HEIGHTS.map((size): [string, string] => [name(`lh-${size}`), `calc(${px(size)} * var(${name('text-scale')}))`]),
          ...SPACING.map((step): [string, string] => [name(`spacing-${step}`), px(step)]),
          ...Object.entries(RADII).map(([role, size]): [string, string] => [name(`radius-${role}`), px(size)]),
          [name('control-height'), px(CONTROL_HEIGHT)],
          ...Object.entries(SHADOWS).map(([role, value]): [string, string] => [name(`shadow-${role}`), value]),
        ],
        '    ',
      ),
      '  }',
    ].join('\n'),
  );

  blocks.push(
    [
      '  /* Line heights fall on whole pixels wherever round() exists, so rows stay on the pixel grid at every text size. */',
      '  @supports (width: round(1.4px, 1px)) {',
      '    :root {',
      declarations(
        LINE_HEIGHTS.map((size): [string, string] => [
          name(`lh-${size}`),
          `round(calc(${px(size)} * var(${name('text-scale')})), 1px)`,
        ]),
        '      ',
      ),
      '    }',
      '  }',
    ].join('\n'),
  );

  blocks.push(
    [
      '  /* Text size scales the whole closed type scale as one number. Only the document scales: the derived sizes resolve at :root. */',
      ...Object.entries(TEXT_SIZES)
        .filter(([size]) => size !== DEFAULT_TEXT_SIZE)
        .map(([size, scale]) => `  :root[data-ov-text-size='${size}'] {\n    ${name('text-scale')}: ${scale};\n  }`),
    ].join('\n'),
  );

  blocks.push(
    [
      '  /* Density changes the rows of lists and tables only. */',
      ...DENSITIES.map((density) => {
        const selector =
          density === DEFAULT_DENSITY ? `:root,\n  [data-ov-density='${density}']` : `[data-ov-density='${density}']`;
        return `  ${selector} {\n${declarations(densityEntries(density), '    ')}\n  }`;
      }),
    ].join('\n'),
  );

  blocks.push('  /* Themes: colour roles and color-scheme, nothing else. Every theme defines every role. */');
  for (const theme of themes) {
    const selector =
      theme.id === defaultThemeId ? `:root,\n  [data-ov-theme='${theme.id}']` : `[data-ov-theme='${theme.id}']`;
    const lines = [`  ${selector} {`, `    color-scheme: ${theme.scheme};`];
    for (const [group, roles] of groups) {
      if (theme.id === defaultThemeId) {
        lines.push(`    /* ${group} */`);
      }

      for (const role of roles) {
        lines.push(`    ${name(role)}: ${theme.colors[role as keyof typeof theme.colors]};`);
      }
    }

    lines.push('  }');
    blocks.push(lines.join('\n'));
  }

  return `/* ${BANNER} */\n@layer ov.tokens {\n${blocks.join('\n\n')}\n}\n`;
}

const quote = (value: string): string => `'${value}'`;

/** A union type with one member per line, so the API report shows every member and a rename is a visible diff. */
function unionType(name: string, values: ReadonlyArray<string | number>, format: (value: string | number) => string): string {
  return `export type ${name} =\n${values.map((value) => `  | ${format(value)}`).join('\n')};`;
}

function listConstant(name: string, type: string, values: ReadonlyArray<string | number>, format: (value: string | number) => string): string {
  return `export const ${name} = [\n${values.map((value) => `  ${format(value)},`).join('\n')}\n] as const satisfies readonly ${type}[];`;
}

/** The typed names: ids, scales and every token name, generated from the same manifest the CSS is. */
export function renderTokenNames(themes: readonly ThemeDefinition[], defaultThemeId: string): string {
  const asString = (value: string | number): string => quote(String(value));
  const asNumber = (value: string | number): string => String(value);
  const colorRoles = groups.flatMap(([, roles]) => roles);
  const textSizes = Object.keys(TEXT_SIZES);
  const radiusRoles = Object.keys(RADII);

  return [
    `// ${BANNER}`,
    '',
    `export const THEMES = [\n${themes.map((theme) => `  { id: ${quote(theme.id)}, name: ${quote(theme.name)}, scheme: ${quote(theme.scheme)} },`).join('\n')}\n] as const;`,
    'export type ThemeId = (typeof THEMES)[number][\'id\'];',
    'export type ThemeScheme = (typeof THEMES)[number][\'scheme\'];',
    'export type ThemeSummary = (typeof THEMES)[number];',
    `export const DEFAULT_THEME_ID: ThemeId = ${quote(defaultThemeId)};`,
    '',
    unionType('Density', DENSITIES, asString),
    listConstant('DENSITIES', 'Density', DENSITIES, asString),
    `export const DEFAULT_DENSITY: Density = ${quote(DEFAULT_DENSITY)};`,
    '',
    unionType('TextSize', textSizes, asString),
    listConstant('TEXT_SIZES', 'TextSize', textSizes, asString),
    `export const DEFAULT_TEXT_SIZE: TextSize = ${quote(DEFAULT_TEXT_SIZE)};`,
    '',
    unionType('SpacingStep', SPACING, asNumber),
    listConstant('SPACING_STEPS', 'SpacingStep', SPACING, asNumber),
    '',
    unionType('RadiusRole', radiusRoles, asString),
    listConstant('RADIUS_ROLES', 'RadiusRole', radiusRoles, asString),
    '',
    unionType('ColorRole', colorRoles, asString),
    listConstant('COLOR_ROLES', 'ColorRole', colorRoles, asString),
    '',
    unionType('TokenName', tokenNames(), asString),
    listConstant('TOKEN_NAMES', 'TokenName', tokenNames(), asString),
    '',
  ].join('\n');
}
